START_DATE = datetime(2024, 1, 1)
END_DATE = datetime(2024, 12, 31)
TOTAL_DAYS = (END_DATE - START_DATE).days


def random_date(start, end):
    delta = end - start
    random_seconds = random.randint(0, int(delta.total_seconds()))
    return start + timedelta(seconds=random_seconds)


def generate_dataset(num_customers=1200, is_sample=False):
    """
    Generates synthetic academic datasets unified by customer_id.
    Ensures persona consistency while adding realistic data-cleaning challenges.
    """
    customers = []
    persona_choices = [p["name"] for p in PERSONAS]
    persona_weights = [p["weight"] for p in PERSONAS]
    persona_map = {p["name"]: p for p in PERSONAS}

    # 1. Generate Customer Profile Base
    for i in range(1, num_customers + 1):
        cid = f"CUST_{i:04d}" if not is_sample else f"CUST_S_{i:03d}"
        chosen_persona_name = random.choices(persona_choices, weights=persona_weights, k=1)[0]
        customers.append({
            "customer_id": cid,
            "persona": persona_map[chosen_persona_name]
        })

    transactions = []
    web_activities = []
    social_interactions = []

    txn_counter = 1
    web_counter = 1
    soc_counter = 1

    for cust in customers:
        cid = cust["customer_id"]
        persona = cust["persona"]

        # ----------------------------------------------------
        # Transactions Generation
        # ----------------------------------------------------
        # For At_Risk personas, restrict purchases to early months
        if persona["name"] == "At_Risk_Dissatisfied":
            tx_start = START_DATE
            tx_end = START_DATE + timedelta(days=120)
        else:
            tx_start = START_DATE
            tx_end = END_DATE

        num_tx = random.randint(persona["tx_count_range"][0], persona["tx_count_range"][1])
        if is_sample:
            num_tx = max(1, num_tx // 3)

        for _ in range(num_tx):
            txn_id = f"TXN_{txn_counter:06d}"
            txn_counter += 1
            txn_date = random_date(tx_start, tx_end)

            # Choose product biased by persona's preferred categories
            if random.random() < 0.75:
                category_choices = [p for p in PRODUCT_CATALOG if p["category"] in persona["preferred_categories"]]
                product = random.choice(category_choices)
            else:
                product = random.choice(PRODUCT_CATALOG)

            quantity = random.choices([1, 2, 3, 4, 5], weights=[0.65, 0.20, 0.08, 0.04, 0.03])[0]
            unit_price = product["base_price"]
            
            # Apply occasional realistic discount (5% to 15%)
            discount = random.choice([0.0, 0.05, 0.10, 0.15]) if random.random() < 0.35 else 0.0
            total_amount = round(quantity * unit_price * (1.0 - discount), 2)

            # Order Status
            if random.random() < persona["cancel_rate"]:
                status = random.choice(["Cancelled", "Refunded"])
            else:
                status = "Completed"

            # Payment Method with realistic missing value edge-case for data cleaning test (0.5%)
            if random.random() < 0.005:
                payment_method = ""  # Intentional missing value for PySpark cleaning
            else:
                payment_method = random.choice(PAYMENT_METHODS)

            transactions.append({
                "transaction_id": txn_id,
                "customer_id": cid,
                "transaction_date": txn_date.strftime("%Y-%m-%d %H:%M:%S"),
                "product_id": product["id"],
                "product_category": product["category"],
                "product_name": product["name"],
                "quantity": quantity,
                "unit_price": f"{unit_price:.2f}",
                "discount_percent": f"{discount * 100:.1f}",
                "total_amount": f"{total_amount:.2f}",
                "payment_method": payment_method,
                "order_status": status
            })

        # ----------------------------------------------------
        # Web Activity Generation
        # ----------------------------------------------------
        num_sessions = random.randint(persona["web_sessions_range"][0], persona["web_sessions_range"][1])
        if is_sample:
            num_sessions = max(2, num_sessions // 3)

        for _ in range(num_sessions):
            session_id = f"SESS_{web_counter // 4 + 1:06d}"
            device = random.choice(DEVICE_TYPES)
            traffic = random.choice(TRAFFIC_SOURCES)
            session_date = random_date(START_DATE, END_DATE)

            # Simulate session page-sequence: view home -> search/category -> view product -> cart
            actions_in_session = random.randint(2, 6)
            curr_time = session_date

            for step in range(actions_in_session):
                act_id = f"WEB_{web_counter:06d}"
                web_counter += 1
                curr_time = curr_time + timedelta(seconds=random.randint(15, 180))

                if step == 0:
                    action_type = "page_view"
                    page_url = "/home"
                    prod_id = ""
                elif step == 1:
                    action_type = "search"
                    pref_cat = random.choice(persona["preferred_categories"]).lower().replace(" ", "-")
                    page_url = f"/category/{pref_cat}"
                    prod_id = ""
                else:
                    action_type = random.choices(
                        ["product_view", "add_to_cart", "wishlist", "checkout_start"],
                        weights=[0.60, 0.22, 0.12, 0.06]
                    )[0]
                    # Select product aligned with user's category affinity
                    cat_prods = [p for p in PRODUCT_CATALOG if p["category"] in persona["preferred_categories"]]
                    selected_prod = random.choice(cat_prods if cat_prods else PRODUCT_CATALOG)
                    prod_id = selected_prod["id"]
                    page_url = f"/product/{prod_id.lower()}"

                duration = random.randint(5, 300)

                web_activities.append({
                    "activity_id": act_id,
                    "customer_id": cid,
                    "session_id": session_id,
                    "timestamp": curr_time.strftime("%Y-%m-%d %H:%M:%S"),
                    "page_url": page_url,
                    "action_type": action_type,
                    "product_id": prod_id,
                    "duration_seconds": duration,
                    "device_type": device,
                    "traffic_source": traffic
                })

        # ----------------------------------------------------
        # Social Media Interaction Generation
        # ----------------------------------------------------
        num_social = random.randint(persona["social_activity_range"][0], persona["social_activity_range"][1])
        if is_sample:
            num_social = max(1, num_social // 3)

        for _ in range(num_social):
            soc_id = f"SOC_{soc_counter:06d}"
            soc_counter += 1
            soc_date = random_date(START_DATE, END_DATE)
            platform = random.choice(SOCIAL_PLATFORMS)
            interaction_type = random.choices(
                ["review", "comment", "mention", "like", "share", "direct_message"],
                weights=[0.30, 0.25, 0.15, 0.15, 0.10, 0.05]
            )[0]

            # Sentiment distribution based on persona
            base_sent = persona["avg_sentiment"]
            noise = random.uniform(-0.35, 0.35)
            sentiment_score = max(-1.0, min(1.0, base_sent + noise))

            if sentiment_score > 0.20:
                sentiment = "Positive"
                feedback_text = random.choice(POSITIVE_FEEDBACK_TEXTS)
            elif sentiment_score < -0.20:
                sentiment = "Negative"
                feedback_text = random.choice(NEGATIVE_FEEDBACK_TEXTS)
            else:
                sentiment = "Neutral"
                feedback_text = random.choice(NEUTRAL_FEEDBACK_TEXTS)

            engagement_score = int(max(5, min(100, (sentiment_score + 1.0) * 45 + random.randint(0, 15))))
            associated_cat = random.choice(persona["preferred_categories"])

            social_interactions.append({
                "interaction_id": soc_id,
                "customer_id": cid,
                "timestamp": soc_date.strftime("%Y-%m-%d %H:%M:%S"),
                "platform": platform,
                "interaction_type": interaction_type,
                "sentiment": sentiment,
                "sentiment_score": f"{sentiment_score:.3f}",
                "engagement_score": engagement_score,
                "feedback_content": feedback_text,
                "associated_category": associated_cat
            })

    # Add deliberate slight duplicate records (~0.2%) to raw datasets to verify PySpark deduplication
    if not is_sample:
        for _ in range(25):
            dup_txn = dict(random.choice(transactions))
            transactions.append(dup_txn)
        for _ in range(35):
            dup_web = dict(random.choice(web_activities))
            web_activities.append(dup_web)

    # Sort records chronologically
    transactions.sort(key=lambda x: x["transaction_date"])
    web_activities.sort(key=lambda x: x["timestamp"])
    social_interactions.sort(key=lambda x: x["timestamp"])

    return transactions, web_activities, social_interactions


def write_csv(filepath, rows, fieldnames):
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    with open(filepath, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


